      <div style="background-color: transparent">
        <component
          :is="renderType"
          @view="receiveId"
          @edit="edit"
          @create="create"
          @view-list="viewList"
          :form-action="formAction"
          :actividad-id="actividadId"
        >
        </component>
      </div>
    </div>
  </div>
</template>


<script>
import ListaActividades from "./ListaActividades.vue";
import FormActividades from "./FormActividades.vue";
import common from "../../masterdata/common.js";

export default {
  name: "actividades",
  mixins: [common],
  components: {
    "lista-actividades": ListaActividades,
    "form-actividades": FormActividades,
  },
  data() {
    return {
      actividadId: null,
      loading: true,
      renderType: "lista-actividades",
      formAction: "",
    };
  },
  async mounted() {
    this.loading = false;
  },
  methods: {
    receiveId(value) {
      this.formAction = "VIEW";
      this.actividadId = value;
      if (this.actividadId !== null) {
        this.renderType = "form-actividades";
      }
    },
    edit(value) {
      this.formAction = "EDIT";
      this.actividadId = value;
      if (this.actividadId !== null) {
        this.renderType = "form-actividades";
      }
    },
    create() {
      this.formAction = "CREATE";
      this.renderType = "form-actividades";
    },
    viewList(value) {
      this.renderType = value;
    },
  },
  computed: {
    /* renderType() {
      return "lista-actividades";
    }, */
  },
};
</script>

